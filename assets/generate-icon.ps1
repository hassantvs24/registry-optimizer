# generate-icon.ps1 — renders RegistryOptimizer\Resources\app.ico (multi-size PNG-in-ICO).
# Theme: registry cylinder on an accent-blue rounded square (matches the app's dark theme).
$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.Drawing

$outDir = Split-Path -Parent $PSScriptRoot      # project root
$icoPath = Join-Path $outDir 'RegistryOptimizer\Resources\app.ico'
New-Item -ItemType Directory -Force -Path (Split-Path $icoPath) | Out-Null

function Render-Png([int]$size) {
    $bmp = New-Object System.Drawing.Bitmap $size, $size, ([System.Drawing.Imaging.PixelFormat]::Format32bppArgb)
    $g = [System.Drawing.Graphics]::FromImage($bmp)
    $g.SmoothingMode = [System.Drawing.Drawing2D.SmoothingMode]::AntiAlias
    $s = $size / 256.0   # scale factor from the 256 design space

    # Rounded-square accent background
    $accent = [System.Drawing.Color]::FromArgb(255, 59, 130, 246)   # #3B82F6
    $radius = 52 * $s
    $path = New-Object System.Drawing.Drawing2D.GraphicsPath
    $r = [System.Drawing.RectangleF]::new(0.0, 0.0, ($size - 1), ($size - 1))
    $d = $radius * 2
    $path.AddArc($r.X, $r.Y, $d, $d, 180, 90)
    $path.AddArc($r.Right - $d, $r.Y, $d, $d, 270, 90)
    $path.AddArc($r.Right - $d, $r.Bottom - $d, $d, $d, 0, 90)
    $path.AddArc($r.X, $r.Bottom - $d, $d, $d, 90, 90)
    $path.CloseFigure()
    $g.FillPath((New-Object System.Drawing.SolidBrush $accent), $path)

    # Registry cylinder (drum): white body + top ellipse, darker arc at the base
    $white = [System.Drawing.Brushes]::White
    $bodyX = 66 * $s; $bodyW = 124 * $s
    $topY  = 86 * $s; $topH = 40 * $s
    $baseY = 186 * $s
    $g.FillRectangle($white, $bodyX, $topY, $bodyW, ($baseY - $topY))
    $g.FillEllipse($white, $bodyX, ($topY - $topH / 2), $bodyW, $topH)
    # base ellipse outline in darker blue for curvature
    $pen = New-Object System.Drawing.Pen ([System.Drawing.Color]::FromArgb(255, 30, 64, 175)), (7 * $s)
    $g.DrawEllipse($pen, $bodyX, ($baseY - $topH / 2), $bodyW, $topH)

    # small sparkle, top-right — the "optimizer" touch
    $cx = 200 * $s; $cy = 52 * $s; $k = 20 * $s
    $spark = New-Object System.Drawing.Drawing2D.GraphicsPath
    $spark.AddLine($cx, ($cy - $k), ($cx + 6 * $s), ($cy - 6 * $s))
    $spark.AddLine(($cx + 6 * $s), ($cy - 6 * $s), ($cx + $k), $cy)
    $spark.AddLine(($cx + $k), $cy, ($cx + 6 * $s), ($cy + 6 * $s))
    $spark.AddLine(($cx + 6 * $s), ($cy + 6 * $s), $cx, ($cy + $k))
    $spark.AddLine($cx, ($cy + $k), ($cx - 6 * $s), ($cy + 6 * $s))
    $spark.AddLine(($cx - 6 * $s), ($cy + 6 * $s), ($cx - $k), $cy)
    $spark.AddLine(($cx - $k), $cy, ($cx - 6 * $s), ($cy - 6 * $s))
    $spark.AddLine(($cx - 6 * $s), ($cy - 6 * $s), $cx, ($cy - $k))
    $spark.CloseFigure()
    $g.FillPath($white, $spark)

    $g.Dispose()
    $ms = New-Object System.IO.MemoryStream
    $bmp.Save($ms, [System.Drawing.Imaging.ImageFormat]::Png)
    $bmp.Dispose()
    return ,$ms.ToArray()   # comma: keep the byte[] intact against pipeline unrolling
}

# Render the standard icon sizes and assemble the ICO container (PNG-compressed entries).
$sizes = 16, 24, 32, 48, 64, 128, 256
$pngs = @{}
foreach ($sz in $sizes) { $pngs[$sz] = Render-Png $sz }

$ms = New-Object System.IO.MemoryStream
$bw = New-Object System.IO.BinaryWriter $ms
$bw.Write([UInt16]0)            # reserved
$bw.Write([UInt16]1)            # type: icon
$bw.Write([UInt16]$sizes.Count) # count
$dataOffset = 6 + 16 * $sizes.Count
foreach ($sz in $sizes) {
    $bytes = [byte[]]$pngs[$sz]
    $bw.Write([Byte]($sz -band 0xFF))          # width  (0 means 256)
    $bw.Write([Byte]($sz -band 0xFF))          # height
    $bw.Write([Byte]0)                         # color palette
    $bw.Write([Byte]0)                         # reserved
    $bw.Write([UInt16]1)                       # color planes
    $bw.Write([UInt16]32)                      # bits per pixel
    $bw.Write([UInt32]$bytes.Length)           # image size
    $bw.Write([UInt32]$dataOffset)             # image offset
    $dataOffset += $bytes.Length
}
foreach ($sz in $sizes) { $bw.Write([byte[]]$pngs[$sz]) }
[System.IO.File]::WriteAllBytes($icoPath, $ms.ToArray())
$bw.Dispose()
Write-Output "wrote $icoPath"

# Also emit AppIcon.Generated.cs: the icon as base64 + a Create() helper.
# WPF single-file publishing cannot resolve pack:// resources for the window icon,
# so the app sets its icon from embedded bytes instead of XAML.
$csPath = Join-Path $outDir 'RegistryOptimizer\AppIcon.Generated.cs'
$b64 = [Convert]::ToBase64String([byte[]]$pngs[256])
$cs = @"
// <auto-generated>by assets/generate-icon.ps1 — do not edit by hand.</nusing System;
using System.IO;
using System.Windows.Media.Imaging;

namespace RegistryOptimizer;

public static class AppIcon
{
    public static BitmapFrame Create()
    {
        var bytes = Convert.FromBase64String(IconBase64);
        var stream = new MemoryStream(bytes);
        // OnLoad: decode fully so the stream can be disposed immediately.
        return BitmapFrame.Create(stream, BitmapCreateOptions.None, BitmapCacheOption.OnLoad);
    }

    private const string IconBase64 =
        "$b64";
}
"@
[System.IO.File]::WriteAllText($csPath, $cs)
Write-Output "wrote $csPath"
